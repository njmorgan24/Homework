def get_mask_card_number(card_number: str) -> str:
    """
    Возвращает маску номера банковской карты.

    Маска отображается в формате ``XXXX XX** **** XXXX``, где видны первые
    6 цифр и последние 4 цифры, а остальные символы заменены звёздочками.
    Номер разбит на блоки по 4 цифры, разделённые пробелами.

    :param card_number: Номер карты (строка из 16 цифр).
    :return: Замаскированный номер карты.
    """
    return f"{card_number[:4]} {card_number[4:6]}** **** {card_number[-4:]}"


def get_mask_account(account_number: str) -> str:
    """
    Возвращает маску номера банковского счёта.

    Маска отображается в формате ``**XXXX``, где видны только последние
    4 цифры номера, а перед ними стоят две звёздочки.

    :param account_number: Номер счёта (строка минимум из 4 цифр).
    :return: Замаскированный номер счёта.
    """
    return f"**{account_number[-4:]}"
